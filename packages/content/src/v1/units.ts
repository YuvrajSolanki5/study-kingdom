function heroLevels(
  hq: number[],
  essence: number[],
  seconds: number[],
  hp: number[],
  damage: number[],
  abilityPower: number[],
  abilitySeconds: number[],
  aura?: number[],
): HeroLevel[] {
  return hq.map((h, i) => ({
    level: i + 1,
    hq: h,
    cost: { essence: essence[i]! },
    seconds: seconds[i]!,
    hp: hp[i]!,
    damage: damage[i]!,
    abilityPower: abilityPower[i]!,
    abilitySeconds: abilitySeconds[i]!,
    ...(aura ? { auraPercent: aura[i]! } : {}),
  }));
}

