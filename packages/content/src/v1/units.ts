import type { HeroDef, HeroLevel, SiegeDef, SpellDef, SpellLevel, TroopDef, UnitLevel } from '../types.ts';

const MIN = 60;
const HOUR = 3600;
const DAY = 86400;

/** Essence cost and research time for a level that needs the given library level. */
const RESEARCH: Record<number, [number, number]> = {
  1: [600, 30 * MIN],
  2: [2500, 2 * HOUR],
  3: [7000, 4 * HOUR],
  4: [15000, 8 * HOUR],
  5: [28000, 12 * HOUR],
  6: [45000, DAY],
  7: [70000, 1.5 * DAY],
  8: [100000, 2 * DAY],
  9: [140000, 3 * DAY],
};

function unitLevels(library: number[], hp: number[], damage: number[], costScale = 1): UnitLevel[] {
  return library.map((lib, i) => {
    const [essence, seconds] = RESEARCH[lib] ?? [0, 0];
    return {
      level: i + 1,
      libraryLevel: lib,
      researchCost: i === 0 ? {} : { essence: Math.round((essence * costScale) / 100) * 100 },
      researchSeconds: i === 0 ? 0 : seconds,
      hp: hp[i]!,
      damage: damage[i]!,
    };
  });
}

function spellLevels(library: number[], power: number[], duration: number[], costScale = 1): SpellLevel[] {
  return library.map((lib, i) => {
    const [essence, seconds] = RESEARCH[lib] ?? [0, 0];
    return {
      level: i + 1,
      libraryLevel: lib,
      researchCost: i === 0 ? {} : { essence: Math.round((essence * costScale) / 100) * 100 },
      researchSeconds: i === 0 ? 0 : seconds,
      power: power[i]!,
      durationSeconds: duration[i]!,
    };
  });
}

