import type { Cost, DefenseLevelStats, StructureDef, StructureLevel, TrapLevelStats } from '../types.ts';

const MIN = 60;
const HOUR = 3600;
const DAY = 86400;

/** Builds level rows from parallel arrays: hq requirement, gold cost, seconds and hitpoints. */
function rows(
  hq: number[],
  gold: number[],
  seconds: number[],
  hp: number[],
  extra: (i: number) => Partial<StructureLevel> = () => ({}),
  costOf: (g: number) => Cost = (g) => (g ? { gold: g } : {}),
): StructureLevel[] {
  return hq.map((h, i) => ({
    level: i + 1,
    hq: h,
    cost: costOf(gold[i]!),
    seconds: seconds[i]!,
    hp: hp[i]!,
    ...extra(i),
  }));
}

const defense =
  (base: Omit<DefenseLevelStats, 'damage'>, damage: number[]) =>
  (i: number): Partial<StructureLevel> => ({ defense: { ...base, damage: damage[i]! } });

const trap =
  (base: Omit<TrapLevelStats, 'damage' | 'springCapacity'>, damage: number[], spring?: number[]) =>
  (i: number): Partial<StructureLevel> => ({
    trap: { ...base, damage: damage[i]!, ...(spring ? { springCapacity: spring[i]! } : {}) },
  });

