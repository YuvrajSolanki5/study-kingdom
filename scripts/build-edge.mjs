// Bundles packages/sim (with content) into the verify-battle Edge Function so
// the server re-simulates battles with exactly the client's code.
import { build } from 'esbuild';
import { join } from 'node:path';

const root = join(import.meta.dirname, '..');
await build({
  entryPoints: [join(root, 'packages/sim/src/index.ts')],
  outfile: join(root, 'supabase/functions/verify-battle/sim.bundle.js'),
  bundle: true,
  format: 'esm',
  platform: 'neutral',
  target: 'es2022',
  minify: false,
  legalComments: 'none',
  banner: { js: '// Generated by scripts/build-edge.mjs from packages/sim. Do not edit.' },
});
console.log('built supabase/functions/verify-battle/sim.bundle.js');
